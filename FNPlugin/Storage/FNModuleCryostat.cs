        public override string GetInfo()
        {
            if (RuleMode)
            {
                // non-cryogenic resources (rate 0) and a second cryostat for the same resource: nothing to say; an empty
                // string keeps the module out of the list. Not the cached Acts: at part compilation the list may be
                // incomplete when GetInfo runs, and the cache would outlive it.
                if (!(boiloffPercentPerHour > 0) || !FirstForResource())
                    return string.Empty;
                var title = PartResourceLibrary.Instance?.GetDefinition(resourceName)?.displayName ?? resourceName;
                var info = Localizer.Format("#LOC_KSPIE_ModuleCryostat_RuleInfo", title, boiloffPercentPerHour.ToString("0.####"),
                    (CryostatRule.CostFactor * boiloffPercentPerHour).ToString("0.####"));
                // the note common to all fuels of the tank once, under the part's first cryogenic cryostat
                if (part != null)
                    foreach (var m in part.Modules)
                        if (m is FNModuleCryostat c && c.boiloffPercentPerHour > 0)
                        {
                            if (ReferenceEquals(c, this))
                                info += "\n" + Localizer.Format("#LOC_KSPIE_ModuleCryostat_RuleNote");
                            break;
                        }
                return info;
            }
            double envMod = ((convectionMod <= -1.0) ? 0.0 : convectionMod + 1.0 / (convectionMod + 1.0)) * Math.Max(0.0, 300.0 - boilOffTemp) / 300.0;
            return $"{resourceName} @ {boilOffTemp:F1} K\nPower Requirements: {powerReqKW * 0.2 * powerReqMult * envMod:F1} KW";
        }
