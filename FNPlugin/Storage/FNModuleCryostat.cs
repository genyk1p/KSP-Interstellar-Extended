    /// <summary>
    /// KSPIE cryostat: keeps one cryogenic resource of the part cold for electric charge.
    ///
    /// Fork, two models:
    ///   - the player's rule (todo/cooling-unification.md, step 4) when the part config sets boiloffPercentPerHour
    ///     (Patches/CryostatBoiloff.cfg, generated by tools/cooling/cc_cryostat_rates.py in the main repo): the tank loses
    ///     that % of its contents per hour without cooling, cooling costs 1.4 × rate × amount / 1000 EC/s (CryostatRule).
    ///     The rate is fixed per part and resource (insulation, tank size and fuel are in the generated value); nothing
    ///     changes it at run time — not part temperature, atmosphere or TweakScale. With Kerbalism the step runs in Kerbalism's resource
    ///     update — ResourceUpdate on a loaded vessel, the static BackgroundUpdate on an unloaded one — so the cost is
    ///     billed like any Kerbalism consumer and the tank boils only its own contents; IFS's Kerbalism processes
    ///     ("X Boiloff / Heating / Cryo Cooling", driven by hidden per-part resources) are left at zero. Switching cooling
    ///     off when the battery runs low and back on is CryoCooling's guard (CryoPowerGuard); without it a short step
    ///     cools what the charge allows and boils the rest;
    ///   - otherwise the upstream model (part temperature, atmosphere, size; IFS's Kerbalism processes), unchanged.
    /// </summary>
    [KSPModule("Cryostat")]
    class FNModuleCryostat : ResourceSuppliableModule, IRescalable<FNModuleCryostat>
    {
