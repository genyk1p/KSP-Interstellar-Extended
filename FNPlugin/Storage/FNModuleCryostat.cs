        public override void OnStart(StartState state)
        {
            _resourceDefinition = PartResourceLibrary.Instance.GetDefinition(resourceName);
            if (_resourceDefinition == null)
                return;

            _electricChargeDefinition = PartResourceLibrary.Instance.GetDefinition(StockResourceElectricCharge);

            boiloffResourceName = boiloffPrefix + resourceName + boiloffPostfix;
            coolingResourceName = "_" + resourceName + coolingPostfix;
            heatingResourceName = "_" + resourceName + heatingPostfix;

            // compensate for stock solar initialization heating issues
            part.temperature = storedTemp;
            requiresPower = powerReqKW > 0;

            isDisabledField = Fields[nameof(isDisabled)];
            boiloffStrField = Fields[nameof(boiloffStr)];
            powerStatusStrField = Fields[nameof(powerStatusStr)];
            externalTemperatureField = Fields[nameof(externalTemperature)];

            if (state == StartState.Editor)
                return;

            part.temperature = storedTemp;
            part.skinTemperature = storedTemp;

            if (RuleMode)
            {
                // Fork (cooling step 5): the same words as CryoCooling's lines on CryoTanks tanks
                powerStatusStrField.guiName = Localizer.Format("#LOC_KSPIE_ModuleCryostat_Spend");
                boiloffStrField.guiName = Localizer.Format("#LOC_KSPIE_ModuleCryostat_Boiloff");

                // No electric charge buffer is added and no IFS Kerbalism variables: the rule bills Kerbalism (stock
                // requests without it). A buffer an old save carries from the upstream model stays on the part; the
                // variables are emptied, or their processes would keep running.
                ZeroKerbalismVariables(part.Resources);
                return;
            }
            WarnMissingRule();

            // if electricCharge buffer is missing, add it.
            if (!part.Resources.Contains(StockResourceElectricCharge))
            {
                var node = new ConfigNode("RESOURCE");
                node.AddValue("name", StockResourceElectricCharge);
                node.AddValue("maxAmount", powerReqKW > 0 ? powerReqKW / 50 : 1);
                node.AddValue("amount", powerReqKW > 0 ? powerReqKW / 50 : 1);
                part.AddResource(node);
            }

            var cryostatResource = part.Resources.Get(_resourceDefinition.id);
            if (cryostatResource != null && Kerbalism.IsLoaded)
            {
                AddKerbalismVariables();
            }
        }

        private void AddKerbalismVariables()
        {
            if (!part.Resources.Contains(boiloffResourceName))
            {
                var newResourceNode = new ConfigNode("RESOURCE");
                newResourceNode.AddValue("name", boiloffResourceName);
                newResourceNode.AddValue("maxAmount", 1);
                newResourceNode.AddValue("amount", 0);

                part.AddResource(newResourceNode);
            }

            if (!part.Resources.Contains(coolingResourceName))
            {
                var newResourceNode = new ConfigNode("RESOURCE");
                newResourceNode.AddValue("name", coolingResourceName);
                newResourceNode.AddValue("maxAmount", 1);
                newResourceNode.AddValue("amount", 0);

                part.AddResource(newResourceNode);
            }

            if (!part.Resources.Contains(heatingResourceName))
            {
                var newResourceNode = new ConfigNode("RESOURCE");
                newResourceNode.AddValue("name", heatingResourceName);
                newResourceNode.AddValue("maxAmount", 1);
                newResourceNode.AddValue("amount", 0);

                part.AddResource(newResourceNode);
            }
        }

        private void UpdateElectricChargeBuffer(double currentPowerUsage)
        {
            if (Kerbalism.IsLoaded)
                return;

            var electricChargeResource = part.Resources[StockResourceElectricCharge];
            if (electricChargeResource != null && (TimeWarp.fixedDeltaTime != previousDeltaTime || previousPowerUsage != currentPowerUsage))
            {
                var requiredCapacity = 2 * currentPowerUsage * TimeWarp.fixedDeltaTime;
                var bufferRatio = electricChargeResource.maxAmount > 0 ? electricChargeResource.amount / electricChargeResource.maxAmount : 0;

                electricChargeResource.maxAmount = requiredCapacity;
                electricChargeResource.amount = bufferRatio * requiredCapacity;
            }

            previousPowerUsage = currentPowerUsage;
            previousDeltaTime = TimeWarp.fixedDeltaTime;
        }

        public void Update()
        {
            if (_resourceDefinition == null)
                return;

            storedTemp = part.temperature;
            if (initializationCountdown > 0)
                initializationCountdown--;

            var cryostatResource = part.Resources.Get(_resourceDefinition.id);

            if (RuleMode)
            {
                UpdateRuleDisplay(cryostatResource);
                return;
            }

            if (cryostatResource != null)
            {
                if (HighLogic.LoadedSceneIsEditor)
                {
                    isDisabledField.guiActiveEditor = true;
                    return;
                }

                isDisabledField.guiActive = powerReqKW > 0;

                bool coolingIsRelevant = cryostatResource.amount > EmptyAmount && (boilOffRate > 0 || requiresPower);

                powerStatusStrField.guiActive = showPower && requiresPower && coolingIsRelevant;
                boiloffStrField.guiActive = showBoiloff && currentBoiloff > 0.0000001;
                externalTemperatureField.guiActive = showTemp && coolingIsRelevant;

                if (!coolingIsRelevant)
                {
                    currentPowerReq = 0;
                    return;
                }

                var atmosphereModifier = convectionMod == -1 ? 0 : convectionMod + part.atmDensity / (convectionMod + 1);

                externalTemperature = part.temperature;
                if (double.IsNaN(externalTemperature) || double.IsInfinity(externalTemperature))
                {
                    part.temperature = part.skinTemperature;
                    externalTemperature = part.skinTemperature;
                }

                var temperatureModifier = Math.Max(0, externalTemperature - boilOffTemp) / 300; //273.15;

                environmentFactor = atmosphereModifier * temperatureModifier;

                if (powerReqKW > 0)
                {
                    currentPowerReq = powerReqKW * 0.2 * environmentFactor * powerReqMult;
                    UpdatePowerStatusSting();
                }
                else
                    currentPowerReq = 0;

                environmentBoiloff = environmentFactor * boilOffMultiplier * boilOffBase;
            }
            else
            {
                boiloffStrField.guiActive = false;
                powerStatusStrField.guiActive = false;

                if (HighLogic.LoadedSceneIsEditor)
                    isDisabledField.guiActiveEditor = false;
                else
                    isDisabledField.guiActive = false;
            }
        }

        private void UpdatePowerStatusSting()
        {
            powerStatusStr = currentPowerReq < 1.0e+3
                ? receivedPowerKw.ToString("0.00") + " KW / " + currentPowerReq.ToString("0.00") + " KW"
                : currentPowerReq < 1.0e+6
                    ? (receivedPowerKw / 1.0e+3).ToString("0.000") + " MW / " + (currentPowerReq / 1.0e+3).ToString("0.000") + " MW"
                    : (receivedPowerKw / 1.0e+6).ToString("0.000") + " GW / " + (currentPowerReq / 1.0e+6).ToString("0.000") + " GW";
        }

        // FixedUpdate is also called while not staged
        public void FixedUpdate()
        {
            if (_resourceDefinition == null)
                return;

            if (RuleMode)
            {
                RuleFixedUpdate();
                return;
            }

            var cryostatResource = part.Resources.Get(_resourceDefinition.id);
            if (cryostatResource == null)
            {
                // Fork: the tank was switched to another resource. The Kerbalism variables added at start stay on the
                // part; their last values would keep draining this resource from the rest of the vessel (boiloff) and
                // electric charge (cooling).
                maxBoiloff = 0;
                currentBoiloff = 0;
                SetKerbalismBoiloff(0, 0);
                SetKerbalismCooling(0);
                return;
            }
            if (double.IsPositiveInfinity(currentPowerReq) || double.IsNaN(currentPowerReq))
            {
                maxBoiloff = 0;
                SetKerbalismBoiloff(0, 0);
                SetKerbalismCooling(0);
                return;
            }

            var fixedDeltaTime = (double)(decimal)Math.Round(TimeWarp.fixedDeltaTime, 7);

            if (!isDisabled && currentPowerReq > 0)
            {
                UpdateElectricChargeBuffer(Math.Max(currentPowerReq, 0.1 * powerReqKW));

                receivedPowerKw = FixedReceivedChargeKw(currentPowerReq, fixedDeltaTime);
            }
            else
            {
                receivedPowerKw = 0;
                // Fork: cooling off or nothing to cool (empty tank). Upstream left the Kerbalism cooling variables at
                // their last value, and its "Cryo Cooling" process kept drawing that much electric charge.
                SetKerbalismCooling(0);
            }

            var sizeMultiplier = _factor.absolute.quadratic == 0 ? 1 : _factor.absolute.quadratic;

            maxBoiloff = boilOffRate + boilOffAddition * environmentBoiloff * part.partInfo.partSize * sizeMultiplier;

            bool hasExtraBoiloff = initializationCountdown == 0 && powerReqKW > 0 && currentPowerReq > 0 && receivedPowerKw < currentPowerReq && previousReceivedPowerKw < previousPowerReq;

            var powerRatioModifier = currentPowerReq > 0 ? Math.Min(1, Math.Max(0, receivedPowerKw / currentPowerReq)) : 0;

            currentBoiloff = powerRatioModifier < 1 ? maxBoiloff * (1 - powerRatioModifier) : 0;

            // Fork: an empty tank has nothing to boil (KNOWN_ISSUES L1). Update() sets no power requirement for it, so the
            // line above gave it the full boiloff; with Kerbalism that boiloff is a vessel-wide process ("LqdHydrogen
            // Boiloff": input LqdHydrogen x the sum of _LqdHydrogenBoiloff over the vessel) and was taken from the other,
            // properly cooled tanks.
            if (cryostatResource.amount <= EmptyAmount)
                currentBoiloff = 0;

            var boiloffResource = Kerbalism.IsLoaded ? part.Resources[boiloffResourceName] : null;
            if (boiloffResource != null)
            {
                SetKerbalismBoiloff(maxBoiloff, currentBoiloff);
            }
            else if (hasExtraBoiloff && currentBoiloff > minimumBoiloff)
            {
                cryostatResource.amount = Math.Max(0, cryostatResource.amount - currentBoiloff * fixedDeltaTime);
            }
            else
            {
                warningShown = false;
                currentBoiloff = 0;
            }

            boiloffStr = currentBoiloff.ToString("0.000000") + " U/s " + cryostatResource.resourceName;

            if (currentBoiloff > minimumBoiloff && hasExtraBoiloff && part.vessel.isActiveVessel && !warningShown)
            {
                warningShown = true;
                ScreenMessages.PostScreenMessage(Localizer.Format("#LOC_IFS_Cryostat_boiloffMsg", boiloffStr), 5, ScreenMessageStyle.UPPER_CENTER);//"Warning: <<1>> Boiloff"
            }

            previousPowerReq = currentPowerReq;
            previousReceivedPowerKw = receivedPowerKw;
        }

        /// <summary>
        /// Fork: the hidden per-part resource the Kerbalism boiloff process reads (only with Kerbalism; no-op without the
        /// resource). Kerbalism also uses the saved value for an unloaded vessel, until the vessel is loaded again.
        /// </summary>
        private void SetKerbalismBoiloff(double max, double current)
        {
            var boiloffResource = Kerbalism.IsLoaded && boiloffResourceName != null ? part.Resources[boiloffResourceName] : null;
            if (boiloffResource == null)
                return;
            boiloffResource.maxAmount = max * kerbalismBoiloffMultiplier;
            boiloffResource.amount = current * kerbalismBoiloffMultiplier;
        }

        /// <summary>
        /// Fork: the hidden per-part resources of the Kerbalism cooling processes ("Heating" adds boiloff, "Cryo Cooling"
        /// removes it for electric charge), both set to the cooling power in kW; 0 = no cooling and no electric charge
        /// drawn. No-op without Kerbalism or without the resources.
        /// </summary>
        private void SetKerbalismCooling(double kw)
        {
            if (!Kerbalism.IsLoaded || coolingResourceName == null)
                return;
            var coolingResource = part.Resources[coolingResourceName];
            var heatingResource = part.Resources[heatingResourceName];
            if (coolingResource == null || heatingResource == null)
                return;
            if (kw > 0)
            {
                coolingResource.maxAmount = kw;
                heatingResource.maxAmount = kw;
            }
            coolingResource.amount = kw;
            heatingResource.amount = kw;
        }

        private double FixedReceivedChargeKw(double powerReqKw, double deltaTime)
        {
            if (powerReqKw <= float.Epsilon || CheatOptions.InfiniteElectricity)
            {
                SetKerbalismCooling(0);
                return powerReqKw;
            }

            var coolingResource = Kerbalism.IsLoaded ? part.Resources[coolingResourceName] : null;
            var heatingResource = Kerbalism.IsLoaded ? part.Resources[heatingResourceName] : null;

            if (coolingResource != null && heatingResource != null)
            {
                SetKerbalismCooling(powerReqKw);

                part.GetConnectedResourceTotals(_electricChargeDefinition.id, out double amount, out _);

                return amount;
            }

            var receivedChargeKw = ConsumeMegawatts(powerReqKw / GameConstants.ecPerMJ, true, true, true) * GameConstants.ecPerMJ;

            return receivedChargeKw;
        }

        // ------------------------------------------------------------------ fork: the player's rule

        private bool RuleMode => boiloffPercentPerHour >= 0;

        /// <summary>
        /// Rule mode and the part's first cryostat for this resource. Some tanks carry two cryostats for one resource
        /// (the IFS spherical tanks for FusionPellets, IST2501lqd for LqdCO2); only the first boils, bills and shows a
        /// switch, or the tank would lose and pay twice. Cached: the part's module list does not change in flight.
        /// </summary>
        private bool Acts
        {
            get
            {
                if (!RuleMode)
                    return false;
                if (_firstForResource == null)
                    _firstForResource = FirstForResource();
                return _firstForResource.Value;
            }
        }

        private bool? _firstForResource;

        /// <summary>
        /// Fork (cooling step 5), for the editor heat window: the boiloff rate (%/h) of this cryostat's resource without
        /// cooling under the rule (the cooling cost follows from it), or 0 — not the rule, not cryogenic, or a part's
        /// second cryostat for the same resource (inert).
        /// </summary>
        internal double EditorRulePercentPerHour => RuleMode && boiloffPercentPerHour > 0 && FirstForResource() ? boiloffPercentPerHour : 0;

        private bool FirstForResource()
        {
            if (part != null)
                foreach (var m in part.Modules)
                    if (m is FNModuleCryostat c && c.resourceName == resourceName)
                        return ReferenceEquals(c, this);
            return true;
        }

        private CryostatRule.Step _lastStep;
        private bool _hasStep;
        private float _nextDisplay;
        private int _fixedUpdatesWithoutKerbalism;

        private static string _brokerTitle;

        /// <summary>Kerbalism's consumer name for the cooling (its resource windows list consumers by this).</summary>
        private static string BrokerTitle => _brokerTitle ?? (_brokerTitle = Localizer.Format("#LOC_KSPIE_ModuleCryostat_Cryostat"));

        /// <summary>Stored charge the cryostats of the current Kerbalism step have claimed (see ChargeTally).</summary>
        private static readonly ChargeTally Tally = new ChargeTally();

        private static double StoredEc(Dictionary<string, double> availableResources) =>
            availableResources != null && availableResources.TryGetValue(StockResourceElectricCharge, out var a) ? a : 0;

        /// <summary>
        /// Game time this tank's step covers: since its last step (see ruleLastStep), else <paramref name="fallback"/>.
        /// Also records now as the last step.
        /// </summary>
        private static double StepSpan(ref double lastStep, double now, double fallback)
        {
            var span = lastStep > 0 && now > lastStep ? now - lastStep : fallback;
            lastStep = now;
            return span;
        }

        private static readonly HashSet<string> LoggedErrors = new HashSet<string>();

        /// <summary>One KSP.log line per kind of failure (Kerbalism calls us every step).</summary>
        private static void LogOnce(string key, Exception e)
        {
            if (LoggedErrors.Count < 50 && LoggedErrors.Add(key))
                UnityEngine.Debug.LogError("[KSPI]: cryostat " + key + " failed: " + e);
        }

        /// <summary>Kerbalism, loaded vessel, every step (its ResourceUpdateDelegate finds this public method by name).</summary>
        public string ResourceUpdate(Dictionary<string, double> availableResources, List<KeyValuePair<string, double>> resourceChangeRequest)
        {
            // Kerbalism's loop over the loaded vessels has no try/catch: an exception here would cut its whole step.
            try
            {
                if (!Acts || _resourceDefinition == null || vessel == null)
                    return BrokerTitle;
                _fixedUpdatesWithoutKerbalism = 0;

                var resource = part.Resources.Get(_resourceDefinition.id);
                if (resource == null)
                {
                    _hasStep = false;
                    return BrokerTitle;
                }
                // what Kerbalism scales this step's requests by (its elapsed_s is TimeWarp.fixedDeltaTime on loaded vessels)
                double seconds = TimeWarp.fixedDeltaTime;
                double now = Planetarium.GetUniversalTime();
                double span = StepSpan(ref ruleLastStep, now, seconds);
                var available = Tally.Available(vessel.id, now, StoredEc(availableResources));
                var step = CryostatRule.Advance(!isDisabled, boiloffPercentPerHour, resource.amount, available, span,
                    CryostatRule.KerbalismReserveSeconds);
                if (step.EcRate > 0)
                {
                    resourceChangeRequest.Add(new KeyValuePair<string, double>(StockResourceElectricCharge, -step.EcRate));
                    Tally.Claim(step.EcRate * Math.Min(span, CryostatRule.KerbalismReserveSeconds));
                }
                // only this tank boils (a Kerbalism request would spread the loss over every tank of the resource)
                if (step.Boiled > 0)
                    resource.amount = Math.Max(0, resource.amount - step.Boiled);
                _lastStep = step;
                _hasStep = true;
            }
            catch (Exception e)
            {
                LogOnce("loaded step", e);
            }
            return BrokerTitle;
        }

        /// <summary>
        /// Flight, a loaded vessel that Kerbalism does not step (no Kerbalism, or a vessel it does not simulate): the same
        /// rule with stock resource requests — full cooling only for the charge actually drawn this step. ResourceUpdate
        /// resets the count; when Kerbalism resumes after a pause both may run in one frame, once. Not in the editor:
        /// Unity calls FixedUpdate there too, and a tank must not boil or draw charge while the craft is being built.
        /// </summary>
        private void RuleFixedUpdate()
        {
            if (!HighLogic.LoadedSceneIsFlight || vessel == null || !Acts)
                return;
            if (Kerbalism.IsLoaded && _fixedUpdatesWithoutKerbalism < 3)
            {
                _fixedUpdatesWithoutKerbalism++;
                return;
            }
            var resource = part.Resources.Get(_resourceDefinition.id);
            if (resource == null)
            {
                _hasStep = false;
                return;
            }
            double seconds = TimeWarp.fixedDeltaTime;
            double span = StepSpan(ref ruleLastStep, Planetarium.GetUniversalTime(), seconds);
            double cost = CryostatRule.CoolingEcRate(boiloffPercentPerHour, resource.amount);
            // the charge is drawn for this frame; a longer span (catch-up after a load) cools only if this frame did
            double got = !isDisabled && cost > 0 && seconds > 0
                ? part.RequestResource(_electricChargeDefinition.id, cost * seconds)
                : 0;
            var step = CryostatRule.Advance(!isDisabled, boiloffPercentPerHour, resource.amount, got * span / Math.Max(seconds, 1e-9),
                span, span);
            if (step.Boiled > 0)
                resource.amount = Math.Max(0, resource.amount - step.Boiled);
            _lastStep = step;
            _hasStep = true;
        }

        // ReSharper disable once UnusedMember.Global - called by Kerbalism through reflection
        public static string BackgroundUpdate(Vessel v, ProtoPartSnapshot part_snapshot, ProtoPartModuleSnapshot module_snapshot,
            PartModule proto_part_module, Part proto_part, Dictionary<string, double> availableResources,
            List<KeyValuePair<string, double>> resourceChangeRequest, double elapsed_s)
        {
            return BackgroundStep(v, part_snapshot, module_snapshot, proto_part_module, availableResources, resourceChangeRequest, elapsed_s);
        }

        /// <summary>
        /// Kerbalism, unloaded vessel, every background step: the rule on the snapshot. The tank's loss is taken from its
        /// own snapshot resource directly — Kerbalism re-reads snapshot amounts when it syncs the vessel's resources (its
        /// own cryo tanks also Consume() the same amount, the double loss CryoCooling removes; here there is only the
        /// direct take); the charge is requested from Kerbalism. The prefab Kerbalism passes is the module's own (paired
        /// by name and index), so a part's second cryostat for a resource is skipped as on a loaded part.
        /// </summary>
        protected static string BackgroundStep(Vessel v, ProtoPartSnapshot part, ProtoPartModuleSnapshot module, PartModule prefab,
            Dictionary<string, double> availableResources, List<KeyValuePair<string, double>> resourceChangeRequest, double elapsed_s)
        {
            var cryostat = prefab as FNModuleCryostat;
            if (v == null || part == null || module == null || cryostat == null || !cryostat.Acts
                || !(elapsed_s > 0) || double.IsInfinity(elapsed_s))
                return BrokerTitle;

            ZeroKerbalismVariables(part, cryostat);

            ProtoPartResourceSnapshot resource = null;
            for (var i = 0; i < part.resources.Count; i++)
                if (part.resources[i].resourceName == cryostat.resourceName)
                {
                    resource = part.resources[i];
                    break;
                }
            if (resource == null)
                return BrokerTitle;

            var values = module.moduleValues;
            var disabled = bool.TryParse(values.GetValue(nameof(isDisabled)), out var d) ? d : cryostat.isDisabled;
            double now = Planetarium.GetUniversalTime();
            double last = double.TryParse(values.GetValue(nameof(ruleLastStep)), NumberStyles.Float, CultureInfo.InvariantCulture, out var l) ? l : -1;
            double span = StepSpan(ref last, now, elapsed_s);
            values.SetValue(nameof(ruleLastStep), last.ToString("R", CultureInfo.InvariantCulture), true);

            var available = Tally.Available(v.id, now, StoredEc(availableResources));
            var step = CryostatRule.Advance(!disabled, cryostat.boiloffPercentPerHour, resource.amount, available, span,
                CryostatRule.KerbalismReserveSeconds);
            if (step.EcRate > 0)
            {
                resourceChangeRequest.Add(new KeyValuePair<string, double>(StockResourceElectricCharge, -step.EcRate));
                Tally.Claim(step.EcRate * Math.Min(span, CryostatRule.KerbalismReserveSeconds));
            }
            if (step.Boiled > 0)
                resource.amount = Math.Max(0, resource.amount - step.Boiled);
            return BrokerTitle;
        }

        /// <summary>Kerbalism planner in the VAB: what the tank costs (cooling on) or loses (off) with its current contents.</summary>
        public string PlannerUpdate(List<KeyValuePair<string, double>> resourceChangeRequest, CelestialBody body, Dictionary<string, double> environment)
        {
            try
            {
                if (!Acts || _resourceDefinition == null)
                    return BrokerTitle;
                var resource = part.Resources.Get(_resourceDefinition.id);
                if (resource == null)
                    return BrokerTitle;
                if (!isDisabled)
                {
                    var cost = CryostatRule.CoolingEcRate(boiloffPercentPerHour, resource.amount);
                    if (cost > 0)
                        resourceChangeRequest.Add(new KeyValuePair<string, double>(StockResourceElectricCharge, -cost));
                }
                else
                {
                    var boil = CryostatRule.BoiloffPerSecond(boiloffPercentPerHour, resource.amount);
                    if (boil > 0)
                        resourceChangeRequest.Add(new KeyValuePair<string, double>(resourceName, -boil));
                }
            }
            catch (Exception e)
            {
                LogOnce("planner", e);
            }
            return BrokerTitle;
        }

        private static bool? _cryoCoolingLoaded;
        private static readonly HashSet<string> WarnedParts = new HashSet<string>();

        /// <summary>
        /// With CryoCooling installed every cryostat should be on the rule (Patches/CryostatBoiloff.cfg). One that is not —
        /// a part added after the patch was generated (mod update, an IFS patch switched on) — keeps the upstream model,
        /// whose vessel-wide IFS process would also drain the rule tanks of its fuel: say so once per part.
        /// </summary>
        private void WarnMissingRule()
        {
            if (_cryoCoolingLoaded == null)
                _cryoCoolingLoaded = AssemblyLoader.loadedAssemblies.Any(a => a.name == "CryoCooling");
            if (_cryoCoolingLoaded == true && part != null && part.partInfo != null && WarnedParts.Add(part.partInfo.name))
                UnityEngine.Debug.LogWarning("[KSPI]: cryostat of " + part.partInfo.name + " (" + resourceName + ") has no " +
                    "boiloffPercentPerHour: the upstream model runs — regenerate Patches/CryostatBoiloff.cfg (tools/cooling/cc_cryostat_rates.py)");
        }

        /// <summary>The upstream model's hidden per-part resources of this tank's IFS Kerbalism processes, emptied.</summary>
        private void ZeroKerbalismVariables(PartResourceList resources)
        {
            foreach (var name in new[] { boiloffResourceName, coolingResourceName, heatingResourceName })
            {
                var r = name == null ? null : resources[name];
                if (r != null)
                    r.amount = 0;
            }
        }

        private static void ZeroKerbalismVariables(ProtoPartSnapshot part, FNModuleCryostat prefab)
        {
            for (var i = 0; i < part.resources.Count; i++)
            {
                var r = part.resources[i];
                if (r.amount == 0 || !r.resourceName.StartsWith("_") && !r.resourceName.StartsWith(prefab.boiloffPrefix))
                    continue;
                if (r.resourceName == prefab.boiloffPrefix + prefab.resourceName + prefab.boiloffPostfix
                    || r.resourceName == "_" + prefab.resourceName + prefab.coolingPostfix
                    || r.resourceName == "_" + prefab.resourceName + prefab.heatingPostfix)
                    r.amount = 0;
            }
        }

        /// <summary>
        /// Part window under the rule: cooling switch, its cost ("Spend"), and the boiloff — what the tank would lose
        /// without cooling while it is cooled, what it loses while it is not; refreshed twice a second.
        /// </summary>
        private void UpdateRuleDisplay(PartResource resource)
        {
            var relevant = resource != null && boiloffPercentPerHour > 0 && Acts;
            if (HighLogic.LoadedSceneIsEditor)
            {
                isDisabledField.guiActiveEditor = relevant;
                return;
            }
            isDisabledField.guiActive = relevant;
            externalTemperatureField.guiActive = false;
            if (!relevant)
            {
                powerStatusStrField.guiActive = false;
                boiloffStrField.guiActive = false;
                return;
            }
            if (UnityEngine.Time.unscaledTime < _nextDisplay)
                return;
            _nextDisplay = UnityEngine.Time.unscaledTime + 0.5f;

            var cost = CryostatRule.CoolingEcRate(boiloffPercentPerHour, resource.amount);
            var share = isDisabled ? 0 : _hasStep ? _lastStep.CooledShare : 1;
            powerStatusStrField.guiActive = cost > 0;
            powerStatusStr = isDisabled
                ? Localizer.Format("#LOC_KSPIE_ModuleCryostat_RuleOff", cost.ToString("0.###"))
                : share < 0.999
                    ? Localizer.Format("#LOC_KSPIE_ModuleCryostat_RuleShort", (cost * share).ToString("0.###"), cost.ToString("0.###"))
                    : Localizer.Format("#LOC_KSPIE_ModuleCryostat_RuleCost", cost.ToString("0.###"));
            var perHour = CryostatRule.BoiloffPerSecond(boiloffPercentPerHour, resource.amount) * 3600;
            boiloffStrField.guiActive = perHour > 0;
            boiloffStr = share < 0.999
                ? Localizer.Format("#LOC_KSPIE_ModuleCryostat_RuleBoiling", (perHour * (1 - share)).ToString("0.##"), boiloffPercentPerHour.ToString("0.####"))
                : Localizer.Format("#LOC_KSPIE_ModuleCryostat_RuleWouldBoil", boiloffPercentPerHour.ToString("0.####"), perHour.ToString("0.##"));
        }

